//! Four independent SHA-256 lanes in one opaque NEON cleanup boundary.
#![allow(unsafe_code)]

/// Retains four output lanes per work word, clearing unused output capacity.
///
/// # Safety
/// Little-endian AArch64 NEON must hold on every eligible CPU during this call.
#[target_feature(enable = "neon")]
#[inline(never)]
pub unsafe extern "C" fn compress(scratch: &mut [u8; 2752], constants: &[u32; 64]) {
    const {
        assert!(cfg!(target_endian = "little"));
    }
    // SAFETY: Initial 0..256, schedule 256..2304, work 2304..2560 and temporary
    // 2560..2752 are fully initialized owner regions with a 32-byte word stride.
    // Every vector uses only the low 16 bytes of a slot. Initial copy zeros the
    // unused work halves; public fixed loops expand 48 words and run 64 rounds.
    // No secret Rust output, stack or call crosses this side-effecting block.
    // It erases all non-output scratch, X4..6, V0..3 and NZCV before exit.
    // Early clobbers exclude input pointers; preserved D8..15 are untouched.
    unsafe {
        core::arch::asm!(
            "// BRYNJA_SECRET_BEGIN",
            "mov x4, #0",
            "movi v3.16b, #0",
            "2:",
            "ldr q0, [{scratch}, x4]",
            "add x6, {scratch}, x4",
            "add x6, x6, #2304",
            "stp q0, q3, [x6]",
            "add x4, x4, #32",
            "cmp x4, #256",
            "b.ne 2b",
            "mov x4, #768",
            "3:",
            "add x6, {scratch}, x4",
            "sub x6, x6, #480",
            "ldr q0, [x6]",
            "ushr v1.4s, v0.4s, #7",
            "shl v2.4s, v0.4s, #25",
            "orr v1.16b, v1.16b, v2.16b",
            "ushr v2.4s, v0.4s, #18",
            "shl v3.4s, v0.4s, #14",
            "orr v2.16b, v2.16b, v3.16b",
            "eor v1.16b, v1.16b, v2.16b",
            "ushr v0.4s, v0.4s, #3",
            "eor v1.16b, v1.16b, v0.16b",
            "str q1, [{scratch}, #2560]",
            "add x6, {scratch}, x4",
            "sub x6, x6, #64",
            "ldr q0, [x6]",
            "ushr v1.4s, v0.4s, #17",
            "shl v2.4s, v0.4s, #15",
            "orr v1.16b, v1.16b, v2.16b",
            "ushr v2.4s, v0.4s, #19",
            "shl v3.4s, v0.4s, #13",
            "orr v2.16b, v2.16b, v3.16b",
            "eor v1.16b, v1.16b, v2.16b",
            "ushr v0.4s, v0.4s, #10",
            "eor v1.16b, v1.16b, v0.16b",
            "ldr q0, [{scratch}, #2560]",
            "add v1.4s, v1.4s, v0.4s",
            "add x6, {scratch}, x4",
            "sub x6, x6, #512",
            "ldr q0, [x6]",
            "add v1.4s, v1.4s, v0.4s",
            "add x6, x6, #288",
            "ldr q0, [x6]",
            "add v1.4s, v1.4s, v0.4s",
            "str q1, [{scratch}, x4]",
            "add x4, x4, #32",
            "cmp x4, #2304",
            "b.ne 3b",
            "mov x4, #256",
            "mov x5, #0",
            "4:",
            "ldr q0, [{scratch}, #2304]",
            "ushr v1.4s, v0.4s, #2",
            "shl v2.4s, v0.4s, #30",
            "orr v1.16b, v1.16b, v2.16b",
            "ushr v2.4s, v0.4s, #13",
            "shl v3.4s, v0.4s, #19",
            "orr v2.16b, v2.16b, v3.16b",
            "eor v1.16b, v1.16b, v2.16b",
            "ushr v2.4s, v0.4s, #22",
            "shl v3.4s, v0.4s, #10",
            "orr v2.16b, v2.16b, v3.16b",
            "eor v1.16b, v1.16b, v2.16b",
            "str q1, [{scratch}, #2560]",
            "ldr q0, [{scratch}, #2432]",
            "ushr v1.4s, v0.4s, #6",
            "shl v2.4s, v0.4s, #26",
            "orr v1.16b, v1.16b, v2.16b",
            "ushr v2.4s, v0.4s, #11",
            "shl v3.4s, v0.4s, #21",
            "orr v2.16b, v2.16b, v3.16b",
            "eor v1.16b, v1.16b, v2.16b",
            "ushr v2.4s, v0.4s, #25",
            "shl v3.4s, v0.4s, #7",
            "orr v2.16b, v2.16b, v3.16b",
            "eor v1.16b, v1.16b, v2.16b",
            "str q1, [{scratch}, #2592]",
            "ldr q0, [{scratch}, #2432]",
            "ldr q1, [{scratch}, #2464]",
            "ldr q2, [{scratch}, #2496]",
            "eor v1.16b, v1.16b, v2.16b",
            "and v0.16b, v0.16b, v1.16b",
            "eor v0.16b, v0.16b, v2.16b",
            "str q0, [{scratch}, #2624]",
            "ldr q0, [{scratch}, #2304]",
            "ldr q1, [{scratch}, #2336]",
            "ldr q2, [{scratch}, #2368]",
            "and v3.16b, v0.16b, v1.16b",
            "eor v0.16b, v0.16b, v1.16b",
            "and v0.16b, v0.16b, v2.16b",
            "eor v0.16b, v0.16b, v3.16b",
            "str q0, [{scratch}, #2656]",
            "ldr q0, [{scratch}, #2528]",
            "ldr q1, [{scratch}, #2592]",
            "add v0.4s, v0.4s, v1.4s",
            "ldr q1, [{scratch}, #2624]",
            "add v0.4s, v0.4s, v1.4s",
            "ldr q1, [{scratch}, x4]",
            "add v0.4s, v0.4s, v1.4s",
            "add x6, {constants}, x5",
            "ld1r {{v1.4s}}, [x6]",
            "add v0.4s, v0.4s, v1.4s",
            "str q0, [{scratch}, #2688]",
            "ldr q0, [{scratch}, #2560]",
            "ldr q1, [{scratch}, #2656]",
            "add v0.4s, v0.4s, v1.4s",
            "str q0, [{scratch}, #2720]",
            "ldr q0, [{scratch}, #2496]",
            "str q0, [{scratch}, #2528]",
            "ldr q0, [{scratch}, #2464]",
            "str q0, [{scratch}, #2496]",
            "ldr q0, [{scratch}, #2432]",
            "str q0, [{scratch}, #2464]",
            "ldr q0, [{scratch}, #2400]",
            "ldr q1, [{scratch}, #2688]",
            "add v0.4s, v0.4s, v1.4s",
            "str q0, [{scratch}, #2432]",
            "ldr q0, [{scratch}, #2368]",
            "str q0, [{scratch}, #2400]",
            "ldr q0, [{scratch}, #2336]",
            "str q0, [{scratch}, #2368]",
            "ldr q0, [{scratch}, #2304]",
            "str q0, [{scratch}, #2336]",
            "ldr q0, [{scratch}, #2688]",
            "ldr q1, [{scratch}, #2720]",
            "add v0.4s, v0.4s, v1.4s",
            "str q0, [{scratch}, #2304]",
            "add x4, x4, #32",
            "add x5, x5, #4",
            "cmp x5, #256",
            "b.ne 4b",
            "mov x4, #0",
            "5:",
            "add x6, {scratch}, x4",
            "ldr q0, [x6, #2304]",
            "ldr q1, [x6]",
            "add v0.4s, v0.4s, v1.4s",
            "str q0, [x6, #2304]",
            "add x4, x4, #32",
            "cmp x4, #256",
            "b.ne 5b",
            "mov x4, #0",
            "6:",
            "str xzr, [{scratch}, x4]",
            "add x4, x4, #8",
            "cmp x4, #2304",
            "b.ne 6b",
            "mov x4, #2560",
            "7:",
            "str xzr, [{scratch}, x4]",
            "add x4, x4, #8",
            "cmp x4, #2752",
            "b.ne 7b",
            "// BRYNJA_REGISTER_ERASE",
            "movi v0.16b, #0",
            "movi v1.16b, #0",
            "movi v2.16b, #0",
            "movi v3.16b, #0",
            "mov x4, xzr",
            "mov x5, xzr",
            "mov x6, xzr",
            "cmp xzr, xzr",
            "// BRYNJA_SECRET_END",
            scratch = in(reg) scratch.as_mut_ptr(),
            constants = in(reg) constants.as_ptr(),
            out("x4") _, out("x5") _, out("x6") _,
            out("v0") _, out("v1") _, out("v2") _, out("v3") _,
            options(nostack),
        );
    }
}
