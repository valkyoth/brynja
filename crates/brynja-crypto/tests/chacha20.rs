//! Public RFC 8439 examples and stream admission/lifecycle checks.
use brynja_crypto::chacha20::{ChaCha20, Error};

#[path = "chacha20/appendix.rs"]
mod appendix;

#[test]
fn rfc8439_appendices() -> Result<(), Error> {
    for (key, nonce, counter, plain, cipher) in appendix::VECTORS {
        let mut actual = vec![0xa5; plain.len()];
        ChaCha20::new(key, *nonce, counter).apply_keystream(plain, &mut actual)?;
        assert_eq!(actual, cipher);
        let mut stream = ChaCha20::new(key, *nonce, counter);
        for chunk in actual.chunks_mut(63) {
            stream.apply_keystream_in_place(chunk)?;
        }
        assert_eq!(actual, plain);
    }
    Ok(())
}

