//! Baseline hardened Keccak-f[1600] normal-return register boundary.
#![allow(unsafe_code)]

pub(super) fn permute(
    state: &mut [u8; 200],
    columns: &mut [u8; 40],
    theta: &mut [u8; 40],
    rearranged: &mut [u8; 200],
) {
    // SAFETY: Fixed disjoint live operands and the exact public FIPS 202 table.
    unsafe {
        scalar(
            state,
            columns,
            theta,
            rearranged,
            &crate::keccak::ROUND_CONSTANTS,
        )
    };
}

/// # Safety
/// Fixed operands must be live and disjoint; constants must be the FIPS 202
/// round table. Byte arrays may be unaligned. Baseline x86-64 or little-endian
