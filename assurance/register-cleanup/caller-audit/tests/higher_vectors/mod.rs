//! Golden outputs from the independent SP 800-185 Python oracles.
//! Input bytes 0..255, message prefix length 135, empty customization, 256 output bits.
//! KMAC key is input[..32]; TupleHash has one item; ParallelHash B=8.
#[test]
fn higher_probe_workers_match_independent_vectors_and_reject_corruption() {
    use brynja_caller_residue_audit::higher::check_known;
    let mut input = [0_u8; 256];
    for (slot, value) in input.iter_mut().zip(0..=u8::MAX) {
        *slot = value;
    }
    for (name, expected) in VECTORS {
        let mut output = [0xa5; 64];
        assert_eq!(
            check_known(name, &input, &mut output, 135, expected),
            0,
            "{name}"
        );
        assert_eq!(&output[..32], &[0; 32]);
        assert_eq!(&output[32..], &[0xa5; 32]);
        let mut wrong = *expected;
        wrong[0] ^= 1;
        assert_eq!(
            check_known(name, &input, &mut output, 135, &wrong),
            3,
            "{name}"
        );
        assert_eq!(&output[..32], &[0; 32]);
        assert_eq!(&output[32..], &[0xa5; 32]);
    }
}

