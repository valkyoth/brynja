//! Two independent SHA-512 lanes in one opaque NEON cleanup boundary.
#![allow(unsafe_code)]

/// Retains two output lanes per work word, clearing unused output capacity.
///
/// # Safety
/// Little-endian AArch64 NEON must hold on every eligible CPU during this call.
#[target_feature(enable = "neon")]
#[inline(never)]
pub unsafe extern "C" fn compress(scratch: &mut [u8; 3264], constants: &[u64; 80]) {
    const {
        assert!(cfg!(target_endian = "little"));
    }
    // SAFETY: Initial 0..256, schedule 256..2816, work 2816..3072 and temporary
    // 3072..3264 are fully initialized owner regions with a 32-byte word stride.
    // Every vector uses only the low 16 bytes of a slot. Initial copy zeros the
    // unused work halves; public fixed loops expand 64 words and run 80 rounds.
    // No secret Rust output, stack or call crosses this side-effecting block.
    // It erases all non-output scratch, X4..6, V0..3 and NZCV before exit.
    // Early clobbers exclude input pointers; preserved D8..15 are untouched.
    unsafe {
        core::arch::asm!(
            "// BRYNJA_SECRET_BEGIN",
            "mov x4, #0",
            "movi v3.16b, #0",
            "2:",
            "ldr q0, [{scratch}, x4]",
            "add x6, {scratch}, x4",
            "add x6, x6, #2816",
            "stp q0, q3, [x6]",
            "add x4, x4, #32",
            "cmp x4, #256",
            "b.ne 2b",
            "mov x4, #768",
            "3:",
            "add x6, {scratch}, x4",
            "sub x6, x6, #480",
            "ldr q0, [x6]",
            "ushr v1.2d, v0.2d, #1",
            "shl v2.2d, v0.2d, #63",
            "orr v1.16b, v1.16b, v2.16b",
            "ushr v2.2d, v0.2d, #8",
            "shl v3.2d, v0.2d, #56",
            "orr v2.16b, v2.16b, v3.16b",
            "eor v1.16b, v1.16b, v2.16b",
            "ushr v0.2d, v0.2d, #7",
            "eor v1.16b, v1.16b, v0.16b",
            "str q1, [{scratch}, #3072]",
            "add x6, {scratch}, x4",
            "sub x6, x6, #64",
            "ldr q0, [x6]",
            "ushr v1.2d, v0.2d, #19",
            "shl v2.2d, v0.2d, #45",
            "orr v1.16b, v1.16b, v2.16b",
            "ushr v2.2d, v0.2d, #61",
            "shl v3.2d, v0.2d, #3",
            "orr v2.16b, v2.16b, v3.16b",
            "eor v1.16b, v1.16b, v2.16b",
            "ushr v0.2d, v0.2d, #6",
            "eor v1.16b, v1.16b, v0.16b",
            "ldr q0, [{scratch}, #3072]",
            "add v1.2d, v1.2d, v0.2d",
            "add x6, {scratch}, x4",
            "sub x6, x6, #512",
            "ldr q0, [x6]",
            "add v1.2d, v1.2d, v0.2d",
            "add x6, x6, #288",
            "ldr q0, [x6]",
            "add v1.2d, v1.2d, v0.2d",
            "str q1, [{scratch}, x4]",
            "add x4, x4, #32",
            "cmp x4, #2816",
            "b.ne 3b",
            "mov x4, #256",
            "mov x5, #0",
            "4:",
            "ldr q0, [{scratch}, #2816]",
            "ushr v1.2d, v0.2d, #28",
            "shl v2.2d, v0.2d, #36",
            "orr v1.16b, v1.16b, v2.16b",
            "ushr v2.2d, v0.2d, #34",
            "shl v3.2d, v0.2d, #30",
            "orr v2.16b, v2.16b, v3.16b",
            "eor v1.16b, v1.16b, v2.16b",
            "ushr v2.2d, v0.2d, #39",
            "shl v3.2d, v0.2d, #25",
            "orr v2.16b, v2.16b, v3.16b",
            "eor v1.16b, v1.16b, v2.16b",
            "str q1, [{scratch}, #3072]",
            "ldr q0, [{scratch}, #2944]",
            "ushr v1.2d, v0.2d, #14",
            "shl v2.2d, v0.2d, #50",
            "orr v1.16b, v1.16b, v2.16b",
            "ushr v2.2d, v0.2d, #18",
            "shl v3.2d, v0.2d, #46",
            "orr v2.16b, v2.16b, v3.16b",
            "eor v1.16b, v1.16b, v2.16b",
            "ushr v2.2d, v0.2d, #41",
            "shl v3.2d, v0.2d, #23",
            "orr v2.16b, v2.16b, v3.16b",
            "eor v1.16b, v1.16b, v2.16b",
            "str q1, [{scratch}, #3104]",
            "ldr q0, [{scratch}, #2944]",
            "ldr q1, [{scratch}, #2976]",
            "ldr q2, [{scratch}, #3008]",
            "eor v1.16b, v1.16b, v2.16b",
            "and v0.16b, v0.16b, v1.16b",
            "eor v0.16b, v0.16b, v2.16b",
            "str q0, [{scratch}, #3136]",
            "ldr q0, [{scratch}, #2816]",
            "ldr q1, [{scratch}, #2848]",
            "ldr q2, [{scratch}, #2880]",
            "and v3.16b, v0.16b, v1.16b",
            "eor v0.16b, v0.16b, v1.16b",
            "and v0.16b, v0.16b, v2.16b",
            "eor v0.16b, v0.16b, v3.16b",
            "str q0, [{scratch}, #3168]",
            "ldr q0, [{scratch}, #3040]",
            "ldr q1, [{scratch}, #3104]",
            "add v0.2d, v0.2d, v1.2d",
            "ldr q1, [{scratch}, #3136]",
            "add v0.2d, v0.2d, v1.2d",
            "ldr q1, [{scratch}, x4]",
            "add v0.2d, v0.2d, v1.2d",
            "add x6, {constants}, x5",
            "ld1r {{v1.2d}}, [x6]",
            "add v0.2d, v0.2d, v1.2d",
            "str q0, [{scratch}, #3200]",
            "ldr q0, [{scratch}, #3072]",
            "ldr q1, [{scratch}, #3168]",
            "add v0.2d, v0.2d, v1.2d",
            "str q0, [{scratch}, #3232]",
            "ldr q0, [{scratch}, #3008]",
            "str q0, [{scratch}, #3040]",
            "ldr q0, [{scratch}, #2976]",
            "str q0, [{scratch}, #3008]",
            "ldr q0, [{scratch}, #2944]",
            "str q0, [{scratch}, #2976]",
            "ldr q0, [{scratch}, #2912]",
            "ldr q1, [{scratch}, #3200]",
            "add v0.2d, v0.2d, v1.2d",
            "str q0, [{scratch}, #2944]",
            "ldr q0, [{scratch}, #2880]",
            "str q0, [{scratch}, #2912]",
            "ldr q0, [{scratch}, #2848]",
            "str q0, [{scratch}, #2880]",
            "ldr q0, [{scratch}, #2816]",
            "str q0, [{scratch}, #2848]",
            "ldr q0, [{scratch}, #3200]",
            "ldr q1, [{scratch}, #3232]",
            "add v0.2d, v0.2d, v1.2d",
            "str q0, [{scratch}, #2816]",
            "add x4, x4, #32",
            "add x5, x5, #8",
            "cmp x5, #640",
            "b.ne 4b",
            "mov x4, #0",
            "5:",
            "add x6, {scratch}, x4",
            "ldr q0, [x6, #2816]",
            "ldr q1, [x6]",
            "add v0.2d, v0.2d, v1.2d",
            "str q0, [x6, #2816]",
            "add x4, x4, #32",
            "cmp x4, #256",
            "b.ne 5b",
            "mov x4, #0",
            "6:",
            "str xzr, [{scratch}, x4]",
            "add x4, x4, #8",
            "cmp x4, #2816",
            "b.ne 6b",
            "mov x4, #3072",
            "7:",
            "str xzr, [{scratch}, x4]",
            "add x4, x4, #8",
            "cmp x4, #3264",
            "b.ne 7b",
            "// BRYNJA_REGISTER_ERASE",
            "movi v0.16b, #0",
            "movi v1.16b, #0",
            "movi v2.16b, #0",
            "movi v3.16b, #0",
            "mov x4, xzr",
            "mov x5, xzr",
            "mov x6, xzr",
            "cmp xzr, xzr",
            "// BRYNJA_SECRET_END",
            scratch = in(reg) scratch.as_mut_ptr(),
            constants = in(reg) constants.as_ptr(),
            out("x4") _, out("x5") _, out("x6") _,
            out("v0") _, out("v1") _, out("v2") _, out("v3") _,
            options(nostack),
        );
    }
}
