#[test]
fn rfc8439_vectors() -> Result<(), Error> {
    for split in 0..=MESSAGE.len() {
        let mut owner = ChaCha20::new(&KEY, NONCE, 1);
        let mut data = [0xa5; 114];
        let (a, b) = data.split_at_mut(split);
        let (left, right) = MESSAGE.split_at(split);
        owner.apply_keystream(left, a)?;
        b.copy_from_slice(right);
        owner.apply_keystream_in_place(b)?;
        assert_eq!(data, CIPHER);
    }
    let mut bytes = CIPHER;
    let mut owner = ChaCha20::new(&KEY, NONCE, 1);
    for byte in &mut bytes {
        owner.apply_keystream_in_place(core::slice::from_mut(byte))?;
    }
    assert_eq!(&bytes, MESSAGE);
    Ok(())
}

#[test]
fn counter_exhaustion() -> Result<(), Error> {
    let mut last = ChaCha20::new(&KEY, NONCE, u32::MAX);
    let mut expected = [0; 64];
    last.apply_keystream_in_place(&mut expected)?;
    assert_eq!(last.remaining_bytes(), 0);
    for split in 0..=64 {
        let mut owner = ChaCha20::new(&KEY, NONCE, u32::MAX);
        let mut actual = [0; 64];
        let (head, tail) = actual.split_at_mut(split);
        owner.apply_keystream_in_place(head)?;
        let remaining = owner.remaining_bytes();
        let mut sentinel = [0xa5; 65];
        assert_eq!(
            owner.apply_keystream(&[0; 65], &mut sentinel),
            Err(Error::Exhausted)
        );
        assert_eq!(
            owner.apply_keystream_in_place(&mut sentinel),
            Err(Error::Exhausted)
        );
        assert_eq!(
            owner.apply_keystream(&[], &mut sentinel),
            Err(Error::LengthMismatch)
        );
        assert_eq!(sentinel, [0xa5; 65]);
        assert_eq!(owner.remaining_bytes(), remaining);
        owner.apply_keystream_in_place(tail)?;
        assert_eq!(actual, expected);
        owner.apply_keystream(&[], &mut [])?;
        owner.apply_keystream_in_place(&mut [])?;
        assert_eq!(
            owner.apply_keystream_in_place(&mut [0]),
            Err(Error::Exhausted)
        );
    }
    assert_eq!(ChaCha20::new(&KEY, NONCE, 0).remaining_bytes(), 1 << 38);
    Ok(())
}
