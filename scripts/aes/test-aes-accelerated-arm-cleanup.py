#!/usr/bin/env python3
"""ARM cleanup negative controls; synthetic images are not build evidence."""
import importlib.util
from pathlib import Path
import re
import struct
import tomllib
import unittest
from unittest.mock import patch


def module(name, filename):
    spec = importlib.util.spec_from_file_location(name, Path(__file__).with_name(filename))
    value = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(value)
    return value


review = module('arm_cleanup_test_review', 'aes_accelerated_linked_arm_cleanup.py')
prior = module('arm_cleanup_kernel_fixture', 'test-aes-accelerated-linked.py')
runner = prior.runner


def fixture(compiler, panic):
    nm, assembly, original, _ = prior.fixture(review.TARGET)
    image = bytearray(original)
    suffixes = {
        'zeroize': '11brynja_core22secret_memory_volatile23zeroize_region_volatile',
        'destroy_key': '30brynja_aes_accelerated_fixture9lifecycle6aes12811destroy_key',
        'destroy_block': '30brynja_aes_accelerated_fixture9lifecycle13destroy_block',
    }
    rows = {}
    for index, role in enumerate(review.ROLES):
        name = ('_ZN' + suffixes[role] + '17h0000000000000000E' if compiler == '1.90.0' else
                ('_RNvNtNt' if role == 'destroy_key' else '_RNvNt') + 'Cs123_' + suffixes[role])
        size = (20 if compiler == '1.90.0' else 24) if role == 'zeroize' else (
            24 if (compiler, panic) == ('1.99.1', 'unwind') else 12)
        rows[role] = name, 0x1600 + 0x100 * index, size
    bodies = {}
    for role, row in rows.items():
        name, start, size = row
        clear = None if role == 'zeroize' else rows['zeroize']
        lines, raw, sizes = review.template(role, compiler, panic, row, clear)
        image[start - 0x1000:start - 0x1000 + size] = raw
        nm += f'\n{start:016x} {size:016x} t {name}'
        assembly += f'{start:016x} <{name}>:\n'
        for i, line in enumerate(lines):
            word = int.from_bytes(raw[4*i:4*i+4], 'little')
            assembly += f' {start + 4*i:x}: {word:08x} \t{line}\n'
        assembly += '\n'
        bodies[role] = lines, raw, sizes, row
    return nm, assembly, bytes(image), bodies, rows


class AcceleratedArmCleanupTests(unittest.TestCase):
    def test_all_configurations_and_exact_mutation_populations(self):
        for compiler in review.COMPILERS:
            for panic in ('abort', 'unwind'):
                nm, asm, image, _, _ = fixture(compiler, panic)
                for admission in ('static', 'hosted'):
                    result = review.inspect(nm, asm, image, compiler, panic, admission)
                    self.assertEqual(result['rejected_cleanup_mutations'],
                                     55 if compiler == '1.90.0' else 90 if panic == 'unwind' else 60)
                    self.assertEqual(result['kernel_review']['rejected_mutations'], 570)
                    self.assertEqual([x['role'] for x in result['bodies']], list(review.ROLES))

    def test_independent_clear_bytes_and_local_branch_targets(self):
        # Literal encodings independently transcribed from inspected binaries,
        # not a fixture generated by the template under test alone.
        for compiler, expected in (
            ('1.90.0', '810000b4210400f11f140038c1ffff54c0035fd6'),
            ('1.99.1', 'a10000b4210400f11f00003900040091a1ffff54c0035fd6'),
        ):
            row = ('clear', 0x1600, len(expected) // 2)
            lines, raw, sizes = review.template('zeroize', compiler, 'abort', row)
            self.assertEqual(raw, bytes.fromhex(expected))
            self.assertEqual(sizes, [4] * len(lines))
            first = int.from_bytes(raw[:4], 'little')
            self.assertEqual(((first >> 5) & 0x7ffff) * 4, len(raw) - 4)
            last_branch = int.from_bytes(raw[-8:-4], 'little')
            immediate = (last_branch >> 5) & 0x7ffff
            self.assertEqual(len(raw) - 8 + (immediate - 0x80000) * 4, 4)

    def test_independent_destruction_bytes_and_relocated_B_edges(self):
        clear, row = ('clear', 0x1600, 24), ('drop', 0x1700, 24)
        for compiler, panic, expected, offsets in (
            ('1.90.0', 'unwind', '400000b4bfffff17c0035fd6', (4,)),
            ('1.99.1', 'abort', '400000b4bfffff17c0035fd6', (4,)),
            ('1.99.1', 'unwind', '62000036800000b4beffff17400000b4bcffff17c0035fd6', (8, 16)),
        ):
            for role in ('destroy_key', 'destroy_block'):
                _, raw, _ = review.template(role, compiler, panic, row, clear)
                self.assertEqual(raw, bytes.fromhex(expected))
                for offset in offsets:
                    word = int.from_bytes(raw[offset:offset+4], 'little')
                    self.assertEqual(word >> 26, 5)  # B, not BL or an indirect jump.
                    immediate = word & 0x3ffffff
                    signed = immediate - 0x4000000 if immediate & 0x2000000 else immediate
                    self.assertEqual(row[1] + offset + signed * 4, clear[1])
        for target in (0x1601, 0x1700 + 2**27 + 16, -2**27):
            with self.assertRaises(ValueError):
                review.template('destroy_key', '1.99.1', 'unwind', row, ('clear', target, 24))

    def test_symbol_population_identity_extent_and_overlap(self):
        for compiler in review.COMPILERS:
            nm, _, _, _, _ = fixture(compiler, 'unwind')
            self.assertEqual(set(review.candidates(nm)), set(review.ROLES))
            cases = [nm + '\n' + nm.splitlines()[-1], '\n'.join(nm.splitlines()[:-1]),
                     nm.replace('11destroy_key', '14destroy_cached'),
                     nm.replace('6aes12811destroy_key', '6aes19211destroy_key'),
                     nm.replace(' t ', ' D '), nm.replace('0000000000001700', '0000000000001604'),
                     nm.replace('0000000000001700', '0000000000001701'),
                     re.sub(r'(0000000000001600) [0-9a-f]+', r'\1 0000000000000000', nm)]
            for changed in cases:
                self.assertNotEqual(changed, nm, 'negative control must actually change the fixture')
                with self.subTest(compiler=compiler, changed=changed), self.assertRaises(ValueError):
                    review.candidates(changed)

    def test_clear_must_be_reviewed_not_merely_named(self):
        nm, asm, image, bodies, rows = fixture('1.99.1', 'unwind')
        # Consistently change both disassembly and image, so byte binding alone
        # cannot reject a non-clearing helper behind an otherwise correct edge.
        changed = bytearray(image)
        pos = rows['zeroize'][1] - 0x1000 + 8
        changed[pos:pos+4] = bytes.fromhex('00000039')  # strb w0, [x0]
        asm = asm.replace('3900001f \tstrb wzr, [x0]', '39000000 \tstrb w0, [x0]')
        with self.assertRaisesRegex(ValueError, 'ARM cleanup stream changed'):
            review.inspect(nm, asm, bytes(changed), '1.99.1', 'unwind', 'hosted')
        lines, raw, sizes, row = bodies['destroy_key']
        for clear in (('wrong', rows['zeroize'][1], 24), (rows['zeroize'][0], 0x1620, 24), row, None):
            with self.assertRaises(ValueError):
                review.check(lines, raw, sizes, row, image, 'destroy_key', '1.99.1', 'unwind', clear)

    def test_mapping_partition_annotations_and_wrong_architecture(self):
        _, _, image, bodies, rows = fixture('1.99.1', 'unwind')
        lines, raw, sizes, row = bodies['destroy_key']
        args = ('destroy_key', '1.99.1', 'unwind', rows['zeroize'])
        for offset in (0, 18, 32, 52, 54, 56, 68, 0x700):
            changed = bytearray(image); changed[offset] ^= 1
            with self.assertRaises(ValueError):
                review.check(lines, raw, sizes, row, bytes(changed), *args)
        for fields in ([8, 4, 4, 4, 4], [4] * 5, [2] * 12):
            with self.assertRaisesRegex(ValueError, 'ARM cleanup stream changed'):
                review.check(lines, raw, fields, row, image, *args)
        for altered in (lines[0].replace('+0xc', '+0x10'), lines[0].replace('0x170c', '0x1710')):
            with self.assertRaisesRegex(ValueError, 'ARM cleanup stream changed'):
                review.check([altered, *lines[1:]], raw, sizes, row, image, *args)
        changed = bytearray(image)
        struct.pack_into('<H', changed, 18, 62)
        with self.assertRaises(ValueError):
            review.check(lines, raw, sizes, row, bytes(changed), *args)

    def test_unknown_configuration_and_dependency_shortcuts_rejected(self):
        for config in (('other', 'abort', 'static'), ('1.99.1', 'other', 'hosted'), ('1.99.1', 'abort', 'other')):
            with self.assertRaisesRegex(ValueError, 'unreviewed ARM cleanup configuration'):
                review.inspect('', '', b'', *config)
        with patch.object(review.kernels, 'inspect', side_effect=ValueError('kernel rejected')):
            with patch.object(review, 'candidates') as select:
                with self.assertRaisesRegex(ValueError, 'kernel rejected'):
                    review.inspect('', '', b'', '1.99.1', 'abort', 'static')
                select.assert_not_called()

    def test_kernel_and_cleanup_may_not_overlap(self):
        nm, asm, image, _, rows = fixture('1.99.1', 'abort')
        overlap = nm.replace('0000000000001600', '0000000000001100')
        with self.assertRaisesRegex(ValueError, 'overlapping ARM cleanup'):
            review.inspect(overlap, asm, image, '1.99.1', 'abort', 'static')

    def test_runner_modes_fail_before_packaging(self):
        cases = [dict(mode='native', admission='static'),
                 dict(mode='arm-qemu', admission='static', capture_only=True)]
        for other in ('review_cached_public', 'review_cached_secret', 'review_ephemeral_secret',
                      'review_ephemeral_public', 'review_lifecycle'):
            cases.append(dict(mode='arm-qemu', admission='hosted', **{other: True}))
        for options in cases:
            with patch.object(runner.packaged, 'package_sources') as package:
                with self.assertRaises(ValueError):
                    runner.check('1.99.1', review_arm_cleanup=True, **options)
                package.assert_not_called()

    def test_registry_exact_scope_and_dependency_closure(self):
        registry = tomllib.loads((runner.ROOT / 'verification/checks.toml').read_text())
        checks = {c['id']: c for c in registry['checks'] if c.get('category') == 'aes-linked-arm-cleanup'}
        self.assertEqual(set(checks), {f'accelerated-arm-cleanup-{admission}-{endpoint}'
                         for admission in ('static', 'hosted') for endpoint in ('msrv', 'current')})
        for endpoint, tc in (('msrv', '1.90.0'), ('current', '1.99.1')):
            for admission in ('static', 'hosted'):
                check = checks[f'accelerated-arm-cleanup-{admission}-{endpoint}']
                self.assertEqual(check['command'], ['python3', 'scripts/aes/check-aes-accelerated-linked.py',
                    '--toolchain', tc, '--mode', 'arm-qemu', '--admission', admission, '--review-arm-cleanup'])
                for group in ('aes-build', 'aes-accelerated-arm-cleanup', 'aes-accelerated-linked',
                              'aes-accelerated-campaigns', 'aes-packaged', 'compiler', 'hkdf-msrv'):
                    self.assertIn(group, check['inputs'])
                self.assertEqual(check['success']['unique_lines'], [f'AES_ACCELERATED_ARM_CLEANUP_LINKED_PASS: {tc} {admission}; four emulated consumers; volatile clear, retained destruction bodies and round kernels'])


if __name__ == '__main__':
    unittest.main()
